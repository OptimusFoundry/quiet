// Generates the parts of quiet that are derived mechanically, so they can never drift by hand:
//   src/index.ts                    — one export per component, a directory scan of every group
//   src/styles/tokens.generated.ts  — the TokenName type (scripts/gen-tokens.mjs)
import { readdirSync, writeFileSync } from "node:fs";
import { genTokens } from "./gen-tokens.mjs";

const HEADER = "// GENERATED by scripts/gen.mjs from src/components — do not edit.\n";

// Groups in reading order: the primitives first, quiet's larger sets after them.
const GROUPS = [
	"core",
	"forms",
	"display",
	"data",
	"layout",
	"navigation",
	"feedback",
	"overlays",
	"future",
	"charts",
	"chat",
	"app",
];
// Every PascalCase .tsx is public (ChartParts too: the axes and legend charts share).
const isComponent = (f) => /^[A-Z]\w*\.tsx$/.test(f);
const files = GROUPS.flatMap((group) =>
	readdirSync(`src/components/${group}`)
		.filter(isComponent)
		.map((f) => `${group}/${f.slice(0, -4)}`)
		.sort(),
);
writeFileSync(
	"src/index.ts",
	`${HEADER}// Styles first: the @layer order statement must be the first CSS in every bundle (a minifier\n// otherwise drops it and layers rank by first appearance, with q.components above q.base).\nimport "./styles/index.scss";\n${files
		.map((f) => `export * from "./components/${f}";`)
		.join(
			"\n",
		)}\nexport { QuietRoot, type QuietRootProps } from "./QuietRoot";\nexport { applyTheme, type BuiltInTheme, defaultTheme, defineThemes, getTheme, resolveTheme, type ThemeDefinition, type ThemeName, themeNames, themes } from "./styles/themes/themes";\nexport { ThemeProvider, useTheme } from "./styles/themes/ThemeProvider";\nexport { type LinkComponent, type LinkComponentProps, useLinkComponent } from "./lib/link";\nexport { cssVar, type TokenName } from "./styles/tokens.generated";\n`,
);
const tokenCount = genTokens();
console.log(`index.ts: ${files.length} components; ${tokenCount} tokens`);
